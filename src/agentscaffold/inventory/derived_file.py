"""The machine-owned derived file next to the inventory (contract v2, Files).

``scaffold inventory init``, ``refresh`` and ``enable`` write it whole; nothing
edits it by hand. ``check`` and every other reader only read it, through
:func:`apply_derived`, which gives the effective value of each derived field:
the pin in the inventory file, else the derived value, else unresolved.
"""

from __future__ import annotations

import datetime as dt
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from agentscaffold.inventory.schema import Inventory, InventoryError, _text

DERIVED_SCHEMA_VERSION = 1
#: Derived field -> its provenance key (contract v2, Derivation).
PROVENANCE: dict[str, str] = {
    "owner_plan": "owner_from",
    "layer": "layer_from",
    "roadmap_stage": "roadmap_stage_from",
}
PIN = "pin"

_HEADER = """\
# Generated by `scaffold inventory refresh`. Do not edit.
# Derived owner plan, layer and roadmap stage for each component, with the rule
# that produced each value. To override one, set it in the inventory file.
"""


@dataclass
class DerivedEntry:
    owner_plan: str | None = None
    owner_from: str | None = None
    touched_by: list[str] = field(default_factory=list)
    layer: str | list[str] | None = None
    layer_from: str | None = None
    roadmap_stage: str | None = None
    roadmap_stage_from: str | None = None

    def to_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {}
        for key in (
            "owner_plan",
            "owner_from",
            "touched_by",
            "layer",
            "layer_from",
            "roadmap_stage",
            "roadmap_stage_from",
        ):
            value = getattr(self, key)
            if value not in (None, [], ""):
                out[key] = value
        return out


@dataclass
class Derived:
    generated_at: str | None = None
    current_roadmap_stage: str | None = None
    current_roadmap_stage_from: str | None = None
    components: dict[str, DerivedEntry] = field(default_factory=dict)


def derived_path(root: Path, config: Any) -> Path:
    """Configured ``derived_path``, else the inventory path with ``.derived.yaml``."""
    inv = config.inventory
    if getattr(inv, "derived_path", None):
        return Path(root) / str(inv.derived_path)
    base = Path(root) / str(inv.path)
    stem = base.name[: -len(base.suffix)] if base.suffix else base.name
    return base.with_name(f"{stem}.derived.yaml")


def _entry(raw: Any) -> DerivedEntry:
    if not isinstance(raw, dict):
        return DerivedEntry()
    layer = raw.get("layer")
    if isinstance(layer, list):
        layer = [t for t in (_text(v) for v in layer) if t] or None
    else:
        layer = _text(layer)
    touched = raw.get("touched_by") or []
    return DerivedEntry(
        owner_plan=_text(raw.get("owner_plan")),
        owner_from=_text(raw.get("owner_from")),
        touched_by=[t for t in (_text(v) for v in touched) if t]
        if isinstance(touched, list)
        else [],
        layer=layer,
        layer_from=_text(raw.get("layer_from")),
        roadmap_stage=_text(raw.get("roadmap_stage")),
        roadmap_stage_from=_text(raw.get("roadmap_stage_from")),
    )


def parse_derived(text: str, *, label: str = "derived file") -> Derived:
    """Parse derived YAML. Raises InventoryError on a malformed file."""
    try:
        raw = yaml.safe_load(text) or {}
    except yaml.YAMLError as exc:
        raise InventoryError(f"{label} is not valid YAML: {exc}") from exc
    if not isinstance(raw, dict):
        raise InventoryError(f"{label} must be a mapping")
    version = raw.get("schema_version", DERIVED_SCHEMA_VERSION)
    if version != DERIVED_SCHEMA_VERSION:
        raise InventoryError(f"{label} has schema_version {version!r}; this tool reads 1")
    components = raw.get("components") or {}
    if not isinstance(components, dict):
        raise InventoryError(f"{label}: components must be a mapping of id to fields")
    return Derived(
        generated_at=_text(raw.get("generated_at")),
        current_roadmap_stage=_text(raw.get("current_roadmap_stage")),
        current_roadmap_stage_from=_text(raw.get("current_roadmap_stage_from")),
        components={str(k): _entry(v) for k, v in components.items()},
    )


def load_derived(path: Path) -> Derived | None:
    """The derived file at *path*, or None when it does not exist."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise InventoryError(f"cannot read {path}: {exc}") from exc
    return parse_derived(text, label=str(path))


def render_derived(derived: Derived, today: dt.date | None = None) -> str:
    """The derived file's text; component ids sorted so diffs stay small."""
    body: dict[str, Any] = {
        "schema_version": DERIVED_SCHEMA_VERSION,
        "generated_at": derived.generated_at or (today or dt.date.today()).isoformat(),
    }
    if derived.current_roadmap_stage:
        body["current_roadmap_stage"] = derived.current_roadmap_stage
        body["current_roadmap_stage_from"] = derived.current_roadmap_stage_from
    body["components"] = {
        cid: derived.components[cid].to_dict() for cid in sorted(derived.components)
    }
    text = yaml.safe_dump(body, sort_keys=False, default_flow_style=False, allow_unicode=True)
    return _HEADER + text


def apply_derived(inventory: Inventory, derived: Derived | None) -> Inventory:
    """The effective inventory: pins win, then derived values; provenance on each."""
    effective = inventory.model_copy(deep=True)
    effective.derived_loaded = derived is not None
    entries = derived.components if derived is not None else {}
    for component in effective.components:
        entry = entries.get(component.id or "")
        for name, from_key in PROVENANCE.items():
            if getattr(component, name):
                setattr(component, from_key, PIN)
                continue
            value = getattr(entry, name) if entry is not None else None
            if isinstance(value, list):
                value = ", ".join(value) or None
            setattr(component, name, value)
            setattr(component, from_key, getattr(entry, from_key) if value else None)
        if entry is not None and not component.touched_by:
            component.touched_by = list(entry.touched_by)
    if effective.current_roadmap_stage:
        effective.current_roadmap_stage_from = PIN
    elif derived is not None and derived.current_roadmap_stage:
        effective.current_roadmap_stage = derived.current_roadmap_stage
        effective.current_roadmap_stage_from = derived.current_roadmap_stage_from
    return effective


