"""The machine-owned derived file and the effective view (contract v2, Files)."""

from __future__ import annotations

import datetime as dt
from pathlib import Path
from types import SimpleNamespace

import pytest

from agentscaffold.inventory.derived_file import (
    PIN,
    Derived,
    DerivedEntry,
    apply_derived,
    derived_path,
    load_derived,
    parse_derived,
    render_derived,
)
from agentscaffold.inventory.schema import InventoryError, parse_inventory

HUMAN = """\
schema_version: 1
components:
  - id: compose:api
    kind: service
    name: api
    owner_plan: "150"
  - id: compose:cache
    kind: service
    name: cache
  - id: compose:loose
    kind: service
    name: loose
"""


def _derived() -> Derived:
    return Derived(
        generated_at="2026-11-05",
        current_roadmap_stage="2",
        current_roadmap_stage_from="roadmap",
        components={
            "compose:cache": DerivedEntry(
                owner_plan="020",
                owner_from="file_impact_map_create",
                touched_by=["031"],
                layer=["2", "4"],
                layer_from="owner_plan",
                roadmap_stage="3",
                roadmap_stage_from="owner_plan",
            ),
            "compose:api": DerivedEntry(
                owner_plan="999", owner_from="commit", layer="5", layer_from="kind_layers"
            ),  # fmt: skip
            "compose:zz": DerivedEntry(owner_plan="1", owner_from="commit"),
        },
    )


def test_render_then_parse_round_trips() -> None:
    text = render_derived(_derived())
    assert text.startswith("# Generated by `scaffold inventory refresh`. Do not edit.")
    assert text.index("compose:api") < text.index("compose:cache") < text.index("compose:zz")
    again = parse_derived(text)
    assert again.components == _derived().components
    assert again.current_roadmap_stage == "2"
    assert again.generated_at == "2026-11-05"


def test_render_uses_today_without_a_generated_at() -> None:
    text = render_derived(Derived(), dt.date(2026, 1, 2))
    assert "generated_at: '2026-01-02'" in text


@pytest.mark.parametrize(
    "text",
    ["components: [\n", "- a list\n", "schema_version: 2\n", "components: [a, b]\n"],
)
def test_malformed_derived_files_raise(text: str) -> None:
    with pytest.raises(InventoryError):
        parse_derived(text)


def test_load_derived_is_none_when_absent(tmp_path: Path) -> None:
    assert load_derived(tmp_path / "missing.yaml") is None
    path = tmp_path / "d.yaml"
    path.write_text(render_derived(_derived()))
    loaded = load_derived(path)
    assert loaded is not None and "compose:cache" in loaded.components


def test_derived_path_default_and_configured(tmp_path: Path) -> None:
    config = SimpleNamespace(
        inventory=SimpleNamespace(path="docs/ai/system_inventory.yaml", derived_path=None)
    )
    assert derived_path(tmp_path, config) == tmp_path / "docs/ai/system_inventory.derived.yaml"
    config.inventory.derived_path = "out/derived.yaml"
    assert derived_path(tmp_path, config) == tmp_path / "out/derived.yaml"


def test_pins_win_then_derived_values_then_unresolved() -> None:
    effective = apply_derived(parse_inventory(HUMAN), _derived())
    by_id = effective.by_id()
    api, cache, loose = by_id["compose:api"], by_id["compose:cache"], by_id["compose:loose"]

    assert (api.owner_plan, api.owner_from) == ("150", PIN)
    assert (api.layer, api.layer_from) == ("5", "kind_layers")
    assert (cache.owner_plan, cache.owner_from) == ("020", "file_impact_map_create")
    assert (cache.layer, cache.layer_from) == ("2, 4", "owner_plan")
    assert cache.touched_by == ["031"]
    assert (loose.owner_plan, loose.owner_from, loose.layer) == (None, None, None)
    assert effective.derived_loaded
    assert (effective.current_roadmap_stage, effective.current_roadmap_stage_from) == (
        "2",
        "roadmap",
    )


def test_apply_derived_leaves_the_human_inventory_unchanged() -> None:
    human = parse_inventory(HUMAN)
    apply_derived(human, _derived())
    assert human.by_id()["compose:cache"].owner_plan is None


def test_without_a_derived_file_only_pins_resolve() -> None:
    effective = apply_derived(parse_inventory(HUMAN), None)
    assert not effective.derived_loaded
    assert effective.by_id()["compose:api"].owner_from == PIN
    assert effective.by_id()["compose:cache"].owner_plan is None


def test_a_pinned_roadmap_stage_wins() -> None:
    human = parse_inventory('current_roadmap_stage: "4"\n' + HUMAN)
    effective = apply_derived(human, _derived())
    assert (effective.current_roadmap_stage, effective.current_roadmap_stage_from) == ("4", PIN)
